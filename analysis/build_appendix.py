#!/usr/bin/env python3
"""Compute the appendix result tables into results/.

Run:  python analysis/build_appendix.py

Covers the traditional-tool baselines, judge agreement, Gold Standard
per-category rates, the knowledge probe and reasoning quality scores.
"""

from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "analysis"))

from judge_rules import JUDGES_MAJORITY, is_sample_file, target_found
from stats import cohens_kappa, fleiss_kappa

OUT = ROOT / "results"
JAN = ROOT / "runs" / "2026-01"
MAY = ROOT / "runs" / "2026-05"

MODELS = [
    "claude-opus-4-5", "gemini-3-pro", "gpt-5.2", "deepseek-v3-2",
    "llama-4-maverick", "qwen3-coder-plus", "grok-4-fast",
]
LABEL = {
    "claude-opus-4-5": "Claude Opus 4.5", "gemini-3-pro": "Gemini 3 Pro",
    "gpt-5.2": "GPT-5.2", "deepseek-v3-2": "DeepSeek v3.2",
    "llama-4-maverick": "Llama 4 Maverick", "qwen3-coder-plus": "Qwen3-Coder-Plus",
    "grok-4-fast": "Grok 4.3",
}
HEADER = "<!-- Generated by analysis/build_appendix.py. Do not edit by hand. -->\n\n"


def load(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return None


# --------------------------------------------------------------------------
def traditional_baselines() -> list[str]:
    """Compile success and finding counts for Slither and Mythril."""
    lines = [HEADER, "# Traditional tool baselines\n",
             "`compiled` counts records where the tool ran without error.\n"
             "`with findings` counts records reporting at least one finding.\n",
             "\n| Tool | Subset | Records | Compiled | With findings | Total findings |",
             "|---|---|---|---|---|---|"]
    for tool in ("slither", "mythril"):
        for subset in ("ds", "tc", "gs", "negative"):
            root = MAY / "traditional" / tool / subset
            if not root.is_dir():
                continue
            records = compiled = flagged = findings = 0
            for path in root.rglob("p_*.json"):
                data = load(path)
                if data is None:
                    continue
                records += 1
                if data.get("success"):
                    compiled += 1
                n = len(data.get("findings") or [])
                findings += n
                if n:
                    flagged += 1
            if records:
                lines.append(f"| {tool} | {subset} | {records} | {compiled} | {flagged} | {findings} |")
    return lines


# --------------------------------------------------------------------------
def judge_agreement() -> list[str]:
    """Pairwise Cohen's kappa and three-way Fleiss' kappa on GS."""
    lines = ["\n# Judge agreement on GS (run 2026-05, direct prompt)\n",
             "Binary outcome is `complete_found`. Pairs are matched per sample.\n",
             "\n| Pair | n | Agreement | Cohen's kappa |", "|---|---|---|---|"]

    verdicts: dict[str, dict[str, bool]] = defaultdict(dict)
    for judge in JUDGES_MAJORITY:
        for model in MODELS:
            directory = MAY / "judge" / judge / model / "gs" / "direct"
            if not directory.is_dir():
                continue
            for path in directory.iterdir():
                if not is_sample_file(path):
                    continue
                found = target_found(path, "complete_only")
                if found is not None:
                    verdicts[judge][f"{model}/{path.name}"] = found

    judges = list(JUDGES_MAJORITY)
    for i, a in enumerate(judges):
        for b in judges[i + 1:]:
            shared = sorted(set(verdicts[a]) & set(verdicts[b]))
            if not shared:
                continue
            kappa, agree = cohens_kappa(
                [verdicts[a][k] for k in shared], [verdicts[b][k] for k in shared]
            )
            lines.append(f"| {a} vs {b} | {len(shared)} | {100 * agree:.1f}% | {kappa:.3f} |")

    keys = set.intersection(*(set(verdicts[j]) for j in judges)) if all(verdicts[j] for j in judges) else set()
    if keys:
        rows = [[verdicts[j][k] for j in judges] for k in sorted(keys)]
        lines.append(f"\nThree-way Fleiss' kappa over {len(rows)} samples: "
                     f"**{fleiss_kappa(rows):.3f}**")
    return lines


# --------------------------------------------------------------------------
def gs_by_category() -> list[str]:
    """GS detection rate grouped by ground-truth vulnerability type."""
    lines = ["\n# GS detection rate by vulnerability category (run 2026-05)\n",
             "Category comes from the sample's own `ground_truth.vulnerability_type`.\n"
             "Rate is averaged over the seven models, judge glm-4.7.\n",
             "\n| Category | n | Mean TDR |", "|---|---|---|"]

    category: dict[str, str] = {}
    directory = MAY / "detection" / "claude-opus-4-5" / "gs" / "direct"
    if directory.is_dir():
        for path in directory.iterdir():
            if not is_sample_file(path):
                continue
            data = load(path)
            if data:
                sample = (data.get("ground_truth") or {}).get("vulnerability_type") or "unknown"
                category[path.name.replace("d_", "", 1)] = sample

    hits: dict[str, int] = Counter()
    total: dict[str, int] = Counter()
    for model in MODELS:
        judge_dir = MAY / "judge" / "glm-4.7" / model / "gs" / "direct"
        if not judge_dir.is_dir():
            continue
        for path in judge_dir.iterdir():
            if not is_sample_file(path):
                continue
            sample = path.name.replace("j_", "", 1)
            cat = category.get(sample)
            found = target_found(path, "complete_only")
            if cat is None or found is None:
                continue
            total[cat] += 1
            hits[cat] += found

    for cat in sorted(total, key=lambda c: (-total[c], c)):
        n = total[cat] // len(MODELS) if total[cat] >= len(MODELS) else total[cat]
        lines.append(f"| {cat} | {n} | {100 * hits[cat] / total[cat]:.1f} |")
    return lines


# --------------------------------------------------------------------------
def knowledge_probe() -> list[str]:
    """Self-reported familiarity with each sample."""
    lines = ["\n# Knowledge probe (run 2026-01)\n",
             "`knowledge_status` as returned by the probe prompt.\n",
             "\n| Model | Subset | n | Familiar | Familiar % |", "|---|---|---|---|---|"]
    for model in MODELS:
        for subset in ("tc", "gs"):
            directory = JAN / "detection" / model / subset / "knowledge_assessment"
            if not directory.is_dir():
                continue
            counts: Counter = Counter()
            for path in directory.iterdir():
                if not is_sample_file(path):
                    continue
                data = load(path)
                if data:
                    counts[(data.get("knowledge_status") or "unknown").lower()] += 1
            n = sum(counts.values())
            familiar = counts.get("familiar", 0) + counts.get("partial", 0)
            if n:
                lines.append(f"| {LABEL[model]} | {subset} | {n} | {familiar} | "
                             f"{100 * familiar / n:.1f} |")
    return lines


# --------------------------------------------------------------------------
def reasoning_quality() -> list[str]:
    """Mean RCIR, AVA and FSV over matched findings."""
    lines = ["\n# Reasoning quality on matched findings (run 2026-01, DS)\n",
             "Mean judge scores where the target was found, averaged over the\n"
             "three judges. RCIR root cause, AVA attack vector, FSV fix validity.\n",
             "\n| Model | n | RCIR | AVA | FSV |", "|---|---|---|---|---|"]
    fields = [
        ("root_cause_identification", "RCIR"),
        ("attack_vector_validity", "AVA"),
        ("fix_suggestion_validity", "FSV"),
    ]
    for model in MODELS:
        sums = {label: 0.0 for _, label in fields}
        counts = {label: 0 for _, label in fields}
        for judge in JUDGES_MAJORITY:
            for tier in ("tier1", "tier2", "tier3", "tier4"):
                directory = JAN / "judge" / judge / model / "ds" / tier
                if not directory.is_dir():
                    continue
                for path in directory.iterdir():
                    if not is_sample_file(path):
                        continue
                    data = load(path)
                    ta = (data or {}).get("target_assessment") or {}
                    if not ta.get("complete_found"):
                        continue
                    for key, label in fields:
                        block = ta.get(key)
                        if isinstance(block, dict) and isinstance(block.get("score"), (int, float)):
                            sums[label] += float(block["score"])
                            counts[label] += 1
        if counts["RCIR"]:
            cells = " | ".join(
                f"{sums[l] / counts[l]:.3f}" if counts[l] else "--" for _, l in fields
            )
            lines.append(f"| {LABEL[model]} | {counts['RCIR']} | {cells} |")
    return lines


def main() -> None:
    OUT.mkdir(exist_ok=True)
    (OUT / "traditional_baselines.md").write_text("\n".join(traditional_baselines()) + "\n")
    (OUT / "judge_agreement.md").write_text(HEADER + "\n".join(judge_agreement()) + "\n")
    (OUT / "gs_by_category.md").write_text(HEADER + "\n".join(gs_by_category()) + "\n")
    (OUT / "knowledge_probe.md").write_text(HEADER + "\n".join(knowledge_probe()) + "\n")
    (OUT / "reasoning_quality.md").write_text(HEADER + "\n".join(reasoning_quality()) + "\n")
    print("wrote:")
    for name in ("traditional_baselines", "judge_agreement", "gs_by_category",
                 "knowledge_probe", "reasoning_quality"):
        print(f"  results/{name}.md")


if __name__ == "__main__":
    main()
